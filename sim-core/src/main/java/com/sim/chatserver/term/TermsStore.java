@ApplicationScoped
public class TermsStore {
    private static final Logger log = Logger.getLogger(TermsStore.class.getCanonicalName());

    private static final String SUPPRESS_UNUSED = com.sim.chatserver.util.CommonLiteralConstants.SUPPRESS_UNUSED;
    private static final String EMPTY = "";
    private static final String SPACE = " ";
    private static final String DB_PRODUCT_POSTGRES = "postgres";
    private static final String DB_PRODUCT_H2 = "h2";
    private static final String MATCH_TYPE_WILDCARD = com.sim.chatserver.util.CommonLiteralConstants.MATCH_TYPE_WILDCARD;
    private static final String MATCH_TYPE_OTHER = "OTHER";
    private static final String BOOL_TRUE = CommonLiteralConstants.VALUE_TRUE;
    private static final String BOOL_ONE = "1";
    private static final String BOOL_YES = CommonLiteralConstants.VALUE_YES;
    private static final String BOOL_Y = "y";
    private static final String MSG_DB_METADATA_UNAVAILABLE = "Unable to resolve database product metadata";
    private static final String MSG_UPSERT_FALLBACK = "Upsert failed; trying update+insert fallback for term {0}";
    private static final String MSG_CREATE_RETURNING_FALLBACK = "Create term RETURNING fallback path used for term {0}";
    private static final String MSG_UPDATE_RETURNING_FALLBACK = "Update term RETURNING fallback path used for id {0}";
    private static final String MSG_PARSE_ID_FALLBACK = "Unable to parse term id; using default fallback";
    private static final String MSG_MATCH_TEST_FAILED_PREFIX = "Failed to test term '";
    private static final String MSG_INVALID_NUMERIC_PREFIX = "Invalid numeric text in column ";
    private static final String MSG_GET_BOOLEAN_FALLBACK_PREFIX = "ResultSet#getBoolean failed for column ";
    private static final String MSG_GET_BOOLEAN_FALLBACK_SUFFIX = ", falling back to text parsing";
    private static final String MSG_RESULTSET_OBJECT_READ_FAILED_PREFIX = "ResultSet object read failed for column ";
    private static final String DEFAULT_OTHER_DESCRIPTION = "Fallback when no configured term is matched.";
    private static final String SQL_CREATE_TABLE_POSTGRES = "CREATE TABLE IF NOT EXISTS term_definition ("
        + "id SERIAL PRIMARY KEY, "
        + "name TEXT UNIQUE NOT NULL, "
        + "description TEXT NOT NULL, "
        + "match_pattern TEXT NOT NULL DEFAULT '', "
        + "match_type TEXT NOT NULL DEFAULT 'WILDCARD', "
        + "system_flag BOOLEAN NOT NULL DEFAULT FALSE, "
        + "created_at TIMESTAMPTZ NOT NULL DEFAULT now()"
        + ')';
    private static final String SQL_CREATE_TABLE_H2 = "CREATE TABLE IF NOT EXISTS term_definition ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
        + "name VARCHAR(1024) UNIQUE NOT NULL, "
        + "description VARCHAR(4096) NOT NULL, "
        + "match_pattern VARCHAR(8192) NOT NULL DEFAULT '', "
        + "match_type VARCHAR(64) NOT NULL DEFAULT 'WILDCARD', "
        + "system_flag BOOLEAN NOT NULL DEFAULT FALSE, "
        + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
        + ')';
    private static final String SQL_CREATE_TABLE_DEFAULT = "CREATE TABLE IF NOT EXISTS term_definition ("
        + "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
        + "name TEXT UNIQUE NOT NULL, "
        + "description TEXT NOT NULL, "
        + "match_pattern TEXT NOT NULL DEFAULT '', "
        + "match_type TEXT NOT NULL DEFAULT 'WILDCARD', "
        + "system_flag BOOLEAN NOT NULL DEFAULT FALSE, "
        + "created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP"
        + ')';
    private static final String SQL_UPSERT_SYSTEM_TERM = "INSERT INTO term_definition (name, description, match_pattern, match_type, system_flag) "
        + "VALUES (?, ?, ?, ?, TRUE) "
        + "ON CONFLICT (name) DO UPDATE SET "
        + "description = EXCLUDED.description, "
        + "match_pattern = EXCLUDED.match_pattern, "
        + "match_type = EXCLUDED.match_type, "
        + "system_flag = TRUE";
    private static final String SQL_UPDATE_SYSTEM_TERM_BY_NAME = "UPDATE term_definition SET description = ?, match_pattern = ?, match_type = ?, system_flag = TRUE WHERE name = ?";
    private static final String SQL_INSERT_SYSTEM_TERM = "INSERT INTO term_definition (name, description, match_pattern, match_type, system_flag) VALUES (?, ?, ?, ?, TRUE)";
    private static final String SQL_LIST_ALL = "SELECT id, name, description, match_pattern, match_type, system_flag FROM term_definition ORDER BY name ASC";
    private static final String SQL_INSERT_RETURNING_ID = "INSERT INTO term_definition (name, description, match_pattern, match_type, system_flag) VALUES (?, ?, ?, ?, FALSE) RETURNING id";
    private static final String SQL_INSERT_TERM = "INSERT INTO term_definition (name, description, match_pattern, match_type, system_flag) VALUES (?, ?, ?, ?, FALSE)";
    private static final String SQL_SELECT_ID_BY_NAME = "SELECT id FROM term_definition WHERE name = ?";
    private static final String SQL_UPDATE_TERM_RETURNING_FLAG = "UPDATE term_definition SET name = ?, description = ?, match_pattern = ?, match_type = ? WHERE id = ? RETURNING system_flag";
    private static final String SQL_UPDATE_TERM = "UPDATE term_definition SET name = ?, description = ?, match_pattern = ?, match_type = ? WHERE id = ?";
    private static final String SQL_SELECT_SYSTEM_FLAG_BY_ID = "SELECT system_flag FROM term_definition WHERE id = ?";
    private static final String SQL_DELETE_BY_ID = "DELETE FROM term_definition WHERE id = ?";
    private static final String COL_ID = "id";
    private static final String COL_NAME = CommonLiteralConstants.FIELD_NAME;
    private static final String COL_DESCRIPTION = com.sim.chatserver.util.CommonLiteralConstants.KEY_DESCRIPTION;
    private static final String COL_MATCH_PATTERN = "match_pattern";
    private static final String COL_MATCH_TYPE = "match_type";
    private static final String COL_SYSTEM_FLAG = "system_flag";

    public static final String OTHER_PARASOFT_LABEL = "Other Parasoft Match";

    private AppDataSourceHolder dsHolder;

    TermsStore() {
        // proxyable no-arg constructor
    }

    @SuppressWarnings(SUPPRESS_UNUSED)
    private final void readObject(java.io.ObjectInputStream in) throws java.io.IOException {
        throw new java.io.NotSerializableException(getClass().getCanonicalName());
    }

    @SuppressWarnings(SUPPRESS_UNUSED)
    private final void writeObject(java.io.ObjectOutputStream out) throws java.io.IOException {
        throw new java.io.NotSerializableException(getClass().getCanonicalName());
    }

    @Inject
    private void setDataSourceHolder(AppDataSourceHolder dsHolder) {
        this.dsHolder = dsHolder;
    }

    public void ensureTable() throws SQLException {
        try (Connection conn = dsHolder.getDataSource().getConnection()) {
            String product = EMPTY;
            try {
                DatabaseMetaData meta = conn.getMetaData();
                if (meta != null && meta.getDatabaseProductName() != null) {
                    product = meta.getDatabaseProductName().toLowerCase();
                }
            } catch (SQLException e) {
                // Defensive fallback to generic SQL when metadata is unavailable.
                log.log(Level.FINE, MSG_DB_METADATA_UNAVAILABLE, e);
                product = EMPTY;
            }

            final boolean isPostgres = product.contains(DB_PRODUCT_POSTGRES);
            final boolean isH2 = product.contains(DB_PRODUCT_H2);

            final String sql;
            if (isPostgres) {
                sql = SQL_CREATE_TABLE_POSTGRES;
            } else if (isH2) {
                sql = SQL_CREATE_TABLE_H2;
            } else {
                sql = SQL_CREATE_TABLE_DEFAULT;
            }

            try (PreparedStatement stmt = conn.prepareStatement(sql)) {
                stmt.execute();
            }
        }
        ensureDefaultTerms();
    }

    private void ensureDefaultTerms() throws SQLException {
        upsertSystemTerm(OTHER_PARASOFT_LABEL,
                DEFAULT_OTHER_DESCRIPTION,
                EMPTY, MATCH_TYPE_OTHER);
    }

    private void upsertSystemTerm(String name, String description, String pattern, String type) throws SQLException {
        SanitizedTermInput input = sanitizeTermInput(name, description, pattern, type);

        try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(
                SQL_UPSERT_SYSTEM_TERM)) {
            ps.setString(1, input.name);
            ps.setString(2, input.description);
            ps.setString(3, input.pattern);
            ps.setString(4, input.type);
            ps.executeUpdate();
        } catch (SQLException e) {
            log.log(Level.FINE, MSG_UPSERT_FALLBACK, input.name);
            try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement upd = conn.prepareStatement(
                    SQL_UPDATE_SYSTEM_TERM_BY_NAME)) {
                upd.setString(1, input.description);
                upd.setString(2, input.pattern);
                upd.setString(3, input.type);
                upd.setString(4, input.name);
                int updated = upd.executeUpdate();
                if (updated > 0) {
                    return;
                }
            }

            try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ins = conn.prepareStatement(
            SQL_INSERT_SYSTEM_TERM)) {
                ins.setString(1, input.name);
                ins.setString(2, input.description);
                ins.setString(3, input.pattern);
                ins.setString(4, input.type);
                ins.executeUpdate();
            }
        }
    }

    public List<TermDefinition> listAll() throws SQLException {
        List<TermDefinition> terms = new ArrayList<>();
        try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(
                SQL_LIST_ALL); ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                terms.add(new TermDefinition(
                        readNonNegativeLong(rs, COL_ID),
                        readSafeDbText(rs, COL_NAME, 1024),
                        readSafeDbText(rs, COL_DESCRIPTION, 4096),
                        readSafeDbText(rs, COL_MATCH_PATTERN, 8192),
                        readSafeDbText(rs, COL_MATCH_TYPE, 64),
                        rs.getBoolean(COL_SYSTEM_FLAG)
                ));
            }
        }
        return terms;
    }

    public TermDefinition createTerm(String name, String description, String pattern, String type) throws SQLException {
        SanitizedTermInput input = sanitizeTermInput(name, description, pattern, type);

        try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(
            SQL_INSERT_RETURNING_ID)) {
            ps.setString(1, input.name);
            ps.setString(2, input.description);
            ps.setString(3, input.pattern);
            ps.setString(4, input.type);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    return new TermDefinition(rs.getLong(1), input.name, input.description, input.pattern, input.type, false);
                }
            }
        } catch (SQLException e) {
            log.log(Level.FINE, MSG_CREATE_RETURNING_FALLBACK, input.name);
            try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(
                    SQL_INSERT_TERM)) {
                ps.setString(1, input.name);
                ps.setString(2, input.description);
                ps.setString(3, input.pattern);
                ps.setString(4, input.type);
                ps.executeUpdate();
            }
            try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(SQL_SELECT_ID_BY_NAME)) {
                ps.setString(1, input.name);
                try (ResultSet rs = ps.executeQuery()) {
                    if (rs.next()) {
                        return new TermDefinition(rs.getLong(1), input.name, input.description, input.pattern, input.type, false);
                    }
                }
            }
        }
        return null;
    }

    public TermDefinition updateTerm(Long id, String name, String description, String pattern, String type) throws SQLException {
        long termId = parseIdOrDefault(id, -1L);
        if (termId <= 0L) {
            return null;
        }

        if (isSystemTerm(termId)) {
            return null;
        }

        SanitizedTermInput input = sanitizeTermInput(name, description, pattern, type);

        try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(
                SQL_UPDATE_TERM_RETURNING_FLAG)) {
            ps.setString(1, input.name);
            ps.setString(2, input.description);
            ps.setString(3, input.pattern);
            ps.setString(4, input.type);
            ps.setLong(5, termId);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    return new TermDefinition(termId, input.name, input.description, input.pattern, input.type, rs.getBoolean(COL_SYSTEM_FLAG));
                }
            }
        } catch (SQLException e) {
            log.log(Level.FINE, MSG_UPDATE_RETURNING_FALLBACK, id);
            try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(
                    SQL_UPDATE_TERM)) {
                ps.setString(1, input.name);
                ps.setString(2, input.description);
                ps.setString(3, input.pattern);
                ps.setString(4, input.type);
                ps.setLong(5, termId);
                int updated = ps.executeUpdate();
                if (updated > 0) {
                    try (PreparedStatement ps2 = conn.prepareStatement(SQL_SELECT_SYSTEM_FLAG_BY_ID)) {
                        ps2.setLong(1, termId);
                        try (ResultSet rs = ps2.executeQuery()) {
                            if (rs.next()) {
                                return new TermDefinition(termId, input.name, input.description, input.pattern, input.type, rs.getBoolean(COL_SYSTEM_FLAG));
                            }
                        }
                    }
                }
            }
        }
        return null;
    }

    public boolean deleteTerm(Long id) throws SQLException {
        long termId = parseIdOrDefault(id, -1L);
        if (termId <= 0L) {
            return false;
        }

        if (isSystemTerm(termId)) {
            return false;
        }
        try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(SQL_DELETE_BY_ID)) {
            ps.setLong(1, termId);
            return ps.executeUpdate() > 0;
        }
    }

    private long parseIdOrDefault(Long id, long defaultValue) {
        String valueText = Objects.toString(id, Long.toString(defaultValue));
        try {
            return Long.parseLong(valueText);
        } catch (NumberFormatException ex) {
            log.log(Level.FINE, MSG_PARSE_ID_FALLBACK, ex);
            return defaultValue;
        }
    }

    private SanitizedTermInput sanitizeTermInput(String name, String description, String pattern, String type) {
        String sanitizedName = TextSanitizer.sanitizeForStorage(name);
        String sanitizedDescription = TextSanitizer.sanitizeForStorage(description);
        String sanitizedType = normalizeMatchType(type);
        String sanitizedPattern = TextSanitizer.sanitizePatternForStorage(pattern, sanitizedType);
        return new SanitizedTermInput(sanitizedName, sanitizedDescription, sanitizedType, sanitizedPattern);
    }

    private boolean isSystemTerm(long id) throws SQLException {
        if (id <= 0L) {
            return false;
        }
        try (Connection conn = dsHolder.getDataSource().getConnection(); PreparedStatement ps = conn.prepareStatement(SQL_SELECT_SYSTEM_FLAG_BY_ID)) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    return false;
                }
                return readSafeDbBoolean(rs, COL_SYSTEM_FLAG);
            }
        }
    }

    private TermDefinition findFirstMatchingTermForPrompt(String prompt) throws SQLException {
        if (prompt == null || prompt.isEmpty()) {
            return null;
        }
        final String sanitized = TextSanitizer.sanitizeForMatching(prompt);
        if (sanitized.isEmpty()) {
            return null;
        }

        return findFirstMatchingTermForPromptFromTerms(sanitized, listAll());
    }

    private TermDefinition findFirstMatchingTermInPrompts(Iterable<String> prompts) throws SQLException {
        if (prompts == null) {
            return null;
        }

        if (prompts instanceof Collection<?> collection && collection.isEmpty()) {
            return null;
        }

        // optimization: one DB read for all prompts
        final List<TermDefinition> terms = listAll();
        if (terms.isEmpty()) {
            return null;
        }

        for (String prompt : prompts) {
            if (prompt == null || prompt.isEmpty()) {
                continue;
            }
            final String sanitized = TextSanitizer.sanitizeForMatching(prompt);
            if (sanitized.isEmpty()) {
                continue;
            }
            TermDefinition found = findFirstMatchingTermForPromptFromTerms(sanitized, terms);
            if (found != null) {
                return found;
            }
        }
        return null;
    }

    private TermDefinition findFirstMatchingTermForPromptFromTerms(String sanitizedPrompt, List<TermDefinition> terms) {
        TermDefinition bestTerm = null;
        int bestStart = Integer.MAX_VALUE;

        for (TermDefinition td : terms) {
            try {
                Pattern p = TermMatcher.buildStrictPattern(td);
                Matcher m = p.matcher(sanitizedPrompt);
                if (m.find()) {
                    int start = m.start();
                    if (start < bestStart) {
                        bestStart = start;
                        bestTerm = td;
                        if (bestStart == 0) {
                            break;
                        }
                    }
                }
            } catch (IllegalArgumentException e) {
                log.log(Level.FINE, MSG_MATCH_TEST_FAILED_PREFIX + td.getName() + '\'', e);
            }
        }
        return bestTerm;
    }

    private long readNonNegativeLong(ResultSet rs, String column) throws SQLException {
        String text = readSafeDbText(rs, column, 64);
        if (text.isBlank()) {
            return 0L;
        }
        try {
            return Math.max(0L, Long.parseLong(text.trim()));
        } catch (NumberFormatException ex) {
            log.log(Level.FINE, MSG_INVALID_NUMERIC_PREFIX + column, ex);
            return 0L;
        }
    }

    private String readSafeDbText(ResultSet rs, String column, int maxChars) throws SQLException {
        Object raw = readRawDbObject(rs, column);
        if (raw != null) {
            if (raw instanceof byte[] bytes) {
                return normalizeDbText(new String(bytes, java.nio.charset.StandardCharsets.UTF_8), maxChars);
            }
            return normalizeDbText(String.valueOf(raw), maxChars);
        }

        return EMPTY;
    }

    private boolean readSafeDbBoolean(ResultSet rs, String column) throws SQLException {
        try {
            boolean value = rs.getBoolean(column);
            if (!rs.wasNull()) {
                return value;
            }
        } catch (SQLException ex) {
            log.log(Level.FINE, MSG_GET_BOOLEAN_FALLBACK_PREFIX + column + MSG_GET_BOOLEAN_FALLBACK_SUFFIX, ex);
        }

        String text = readSafeDbText(rs, column, 16);
        if (text.isBlank()) {
            return false;
        }
        String normalized = text.trim().toLowerCase(Locale.ROOT);
        return BOOL_TRUE.equals(normalized) || BOOL_ONE.equals(normalized) || BOOL_YES.equals(normalized) || BOOL_Y.equals(normalized);
    }

    private static String normalizeMatchType(String type) {
        if (type == null || type.trim().isEmpty()) {
            return MATCH_TYPE_WILDCARD;
        }
        return type.trim().toUpperCase();
    }

    private String normalizeDbText(String value, int maxChars) {
        if (value == null) {
            return EMPTY;
        }
        String normalized = value.replace('\u0000', ' ').replace(System.lineSeparator(), EMPTY).replace(System.lineSeparator(), SPACE).trim();
        if (maxChars > 0 && normalized.length() > maxChars) {
            return new String(normalized.toCharArray(), 0, maxChars);
        }
        return normalized;
    }

    private Object readRawDbObject(ResultSet rs, String column) {
        try {
            return rs.getObject(column);
        } catch (SQLException ex) {
            log.log(Level.FINE, MSG_RESULTSET_OBJECT_READ_FAILED_PREFIX + column, ex);
            return null;
        }
    }

}

final class SanitizedTermInput {

    final String name;
    final String description;
    final String type;
    final String pattern;

    SanitizedTermInput(String name, String description, String type, String pattern) {
        this.name = name;
        this.description = description;
        this.type = type;
        this.pattern = pattern;
    }
}

